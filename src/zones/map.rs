use std::fs;
use std::io::ErrorKind;
use std::path::PathBuf;

use serde_json::{json, Value};

use super::model::{
    load as load_zones, parse, set_version, Autonomy, Criticality, Selector, SelectorKind, Zone,
};
use super::resolve::select;
use super::review::{actor, audit, directory, log, require_human, write, CONFIRM_LENGTH};
use crate::inventory::Inventory;
use crate::proposals::store::agent_environment;
