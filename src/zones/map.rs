// The compact zone map: .crane/zones.map lists one target per line with its criticality and
// autonomy ("payments/service.py::PaymentService.charge critical assisted"). It is a human's draft:
// nothing in it governs agents until `crane zones approve map` compiles it, through the ordinary
// zone model, into one zone per (criticality, autonomy) group with deterministic ids and writes
// them to .crane/zones/zones-map.zone. The authority engine therefore never learns a new format,
// and the zone set version changes only when an approved map changes the compiled zones.

